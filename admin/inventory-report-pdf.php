<?php
// PDF version of the inventory report (same filters as inventory-report.php)
ob_start();
session_start();
include("inc/config.php");
include("inc/functions.php");
require('fpdf186/fpdf.php');

if (!isset($_SESSION['user']['role']) || $_SESSION['user']['role'] != 'superadmin') {
    header('location: login.php');
    exit;
}

list($from, $to, $category, $stock) = inventory_report_filters($_GET);
$report = get_inventory_report($pdo, $from, $to, $category, $stock);
$summary = $report['summary'];

$category_name = 'All Categories';
if ($category) {
    $statement = $pdo->prepare("SELECT tcat_name FROM tbl_category WHERE tcat_id=?");
    $statement->execute(array($category));
    $category_name = $statement->fetchColumn() ?: $category_name;
}
$stock_names = array('all' => 'All', 'in' => 'In Stock', 'low' => 'Low Stock', 'out' => 'Out of Stock');

// FPDF core fonts are Windows-1252; the peso sign is not in it, so amounts print as "PHP"
function pdf_text($text)
{
    $converted = @iconv('UTF-8', 'windows-1252//TRANSLIT//IGNORE', (string)$text);
    return $converted === false ? (string)$text : $converted;
}
function pdf_money($amount)
{
    return number_format((float)$amount, 2);
}

$columns = array(
    array('#', 10, 'C'),
    array('Product', 72, 'L'),
    array('Category', 35, 'L'),
    array('Price (PHP)', 25, 'R'),
    array('Stock', 18, 'R'),
    array('Status', 27, 'L'),
    array('Units Sold', 22, 'R'),
    array('Sales (PHP)', 34, 'R'),
    array('Stock Value (PHP)', 34, 'R'),
);

function table_header($pdf, $columns)
{
    $pdf->SetFont('Arial', 'B', 9);
    $pdf->SetFillColor(46, 125, 50);
    $pdf->SetTextColor(255, 255, 255);
    foreach ($columns as $c) {
        $pdf->Cell($c[1], 8, $c[0], 1, 0, 'C', true);
    }
    $pdf->Ln();
    $pdf->SetTextColor(0, 0, 0);
    $pdf->SetFont('Arial', '', 9);
}

$pdf = new FPDF('L', 'mm', 'A4');
$pdf->SetMargins(10, 10, 10);
$pdf->SetAutoPageBreak(false);
$pdf->AddPage();

$pdf->SetFont('Arial', 'B', 16);
$pdf->Cell(0, 9, pdf_text("Malou's Garden - Inventory Report"), 0, 1, 'C');
$pdf->SetFont('Arial', '', 10);
$pdf->Cell(0, 6, pdf_text('Sales period: ' . date('M d, Y', strtotime($from)) . ' - ' . date('M d, Y', strtotime($to))
    . '   |   Category: ' . $category_name . '   |   Stock: ' . $stock_names[$stock]), 0, 1, 'C');
$pdf->Cell(0, 6, pdf_text('Stock as of ' . date('M d, Y h:i A') . '   |   Generated by ' . $_SESSION['user']['full_name']), 0, 1, 'C');
$pdf->Ln(3);

// Summary
$pdf->SetFont('Arial', 'B', 10);
$boxes = array(
    'Products' => $summary['products'],
    'Stock on Hand' => number_format($summary['stock_units']) . ' units',
    'Inventory Value' => 'PHP ' . pdf_money($summary['stock_value']),
    'Low Stock (<=' . LOW_STOCK_LEVEL . ')' => $summary['low'],
    'Out of Stock' => $summary['out'],
    'Sales' => 'PHP ' . pdf_money($summary['sales']) . ' (' . number_format($summary['units_sold']) . ' units)',
);
$widths = array(30, 40, 50, 37, 35, 85);
$i = 0;
foreach ($boxes as $label => $value) {
    $pdf->SetFont('Arial', '', 8);
    $x = $pdf->GetX();
    $y = $pdf->GetY();
    $pdf->Cell($widths[$i], 5, pdf_text($label), 'LTR', 2, 'C');
    $pdf->SetFont('Arial', 'B', 10);
    $pdf->Cell($widths[$i], 7, pdf_text($value), 'LBR', 0, 'C');
    $pdf->SetXY($x + $widths[$i], $y);
    $i++;
}
$pdf->Ln(15);

table_header($pdf, $columns);
foreach ($report['rows'] as $n => $row) {
    if ($pdf->GetY() > 185) {
        $pdf->AddPage();
        table_header($pdf, $columns);
    }
    $values = array(
        $n + 1,
        $row['name'],
        $row['category'],
        pdf_money($row['price']),
        $row['qty'],
        $row['status'],
        $row['units_sold'],
        pdf_money($row['sales']),
        pdf_money($row['stock_value']),
    );
    foreach ($columns as $k => $c) {
        $text = pdf_text($values[$k]);
        // Keep long product names inside their cell
        while ($k == 1 && $pdf->GetStringWidth($text) > $c[1] - 2 && strlen($text) > 3) {
            $text = substr($text, 0, -4) . '...';
        }
        $pdf->Cell($c[1], 7, $text, 1, 0, $c[2]);
    }
    $pdf->Ln();
}

if ($pdf->GetY() > 180) {
    $pdf->AddPage();
}
$pdf->SetFont('Arial', 'B', 9);
$pdf->Cell(142, 8, 'Total', 1, 0, 'R');
$pdf->Cell(18, 8, number_format($summary['stock_units']), 1, 0, 'R');
$pdf->Cell(27, 8, '', 1, 0);
$pdf->Cell(22, 8, number_format($summary['units_sold']), 1, 0, 'R');
$pdf->Cell(34, 8, pdf_money($summary['sales']), 1, 0, 'R');
$pdf->Cell(34, 8, pdf_money($summary['stock_value']), 1, 1, 'R');

$pdf->Ln(3);
$pdf->SetFont('Arial', 'I', 8);
$pdf->MultiCell(0, 5, pdf_text('Sales and units sold count orders whose payment has been confirmed (down payment or full) within the sales period, including POS sales. '
    . 'Low Stock means ' . LOW_STOCK_LEVEL . ' pieces or less.'));

ob_end_clean();
$pdf->Output('I', 'inventory-report-' . $from . '-to-' . $to . '.pdf');
